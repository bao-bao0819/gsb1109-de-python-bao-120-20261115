PATH_PARSER = re.compile(r"([^\[]+)\[(\d+)\]_?")


def extract_path(path):
    '''Parse `key[index]_next_key[next_index]...` sequences into
    lists of (key, index) pairs.

    Parameters
    ----------
    path : str
        The path key to parse

    Returns
    -------
    list
    '''
    return [(t, int(i)) for t, i in PATH_PARSER.findall(path)]


class Group(OrderedDict):
    '''A type for holding collections of arbitrarily nested keys from rows
    and metadata mappings.

    Implemented as an autovivifying :class:`OrderedDict` variant. As such implements
    the :class:`~collections.abc.Mapping` interface.
    '''

    def get_path(self, path, default=None):
        '''As :meth:`get` but over a path key parsed with :func:`extract_path`.

        Parameters
        ----------
        path : str
            The path to search down
        default : object, optional
            The return value when the path is missing

        Returns
        -------
        object
        '''
        tokens = extract_path(path)
        if not tokens:
            return self.get(path, default)
        layer = self
        for k, i in tokens[:-1]:
            i = int(i)
            layer = layer.get(k)
            if layer is None:
                return None
            layer = layer.get(i)
            if layer is None:
                return None
        k, i = tokens[-1]
        i = int(i)
        layer = layer.get(k)
        if layer is None:
            return default
        value = layer.get(i, default)
        return value

    def __missing__(self, key):
        value = self.__class__()
        self[key] = value
        return value


_NULL_STRINGS = {'', 'null', 'none', 'nan', 'n/a', 'na'}


def _is_null(value):
    if value is None:
        return True
    if isinstance(value, float) and value != value:
        return True
    try:
        if pd is not None and not isinstance(value, (str, bytes, tuple, list, set, dict)):
            result = pd.isna(value)
            if isinstance(result, bool) and result:
                return True
    except (TypeError, ValueError):
        pass
    return isinstance(value, str) and value.strip().lower() in _NULL_STRINGS


def _as_text(value):
    if _is_null(value):
        return None
    return str(value).strip()


def _normalize_description(value):
    if _is_null(value):
        return None
    if isinstance(value, (list, tuple)):
        parts = [_as_text(item) for item in value]
        parts = [part for part in parts if part]
        if not parts:
            return None
        if len(parts) == 1:
            return parts[0].strip('[]')
        return '|'.join(parts).strip('[]')
    return _as_text(value)


def _iter_table_records(table):
    """Yield rows of an :class:`_MzTabTable` or a :class:`pandas.DataFrame`."""
    if table is None:
        return
    if isinstance(table, dict):
        rows = table.get('rows', [])
    elif hasattr(table, 'header') and hasattr(table, 'rows'):
        header = table.header or []
        rows = [dict(zip(header, row)) for row in table.rows]
    elif hasattr(table, 'to_dict'):
        rows = table.to_dict('records')
    else:
        rows = table
    for row in rows:
        if isinstance(row, dict):
            yield row
        else:
            yield dict(row)


def _split_accessions(value):
    """Split the accession field of an mzTab row into individual accessions.

    mzTab normally stores one accession per row, but several exporters use
    comma, semicolon or pipe separated lists.  Decorated FASTA identifiers
    such as ``sp|P12345|NAME_HUMAN`` are kept intact.
    """
    if value is None:
        return []
    if isinstance(value, (list, tuple, set)):
        parts = []
        for item in value:
            parts.extend(_split_accessions(item))
        return list(OrderedDict.fromkeys(parts))
    text = _as_text(value)
    if text is None:
        return []
    parts = [part.strip() for part in re.split(r'\s*[;,]\s*', text) if part.strip()]
    out = []
    for part in parts:
        if '|' in part and not re.match(r'^[A-Za-z][A-Za-z0-9_.-]*\|[^|]+\|', part):
            out.extend(piece.strip() for piece in part.split('|') if piece.strip())
        else:
            out.append(part)
    return list(OrderedDict.fromkeys(out))


